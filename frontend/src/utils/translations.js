/**
 * Helper to translate any English text string or key into the requested language
 */
export function translateText(key, lang = "en") {
  if (!key) return "";
  const targetDict = translations[lang] || translations.en;
  
  // 1. Direct key match
  if (targetDict[key] !== undefined) {
    return targetDict[key];
  }

  // 2. Trimmed match
  const trimmed = String(key).trim();
  if (targetDict[trimmed] !== undefined) {
    return targetDict[trimmed];
  }

  // 3. Case-insensitive lookup
  const lower = trimmed.toLowerCase();
  for (const [k, val] of Object.entries(targetDict)) {
    if (k.toLowerCase() === lower) {
      return val;
    }
  }

  // 4. Snake_case conversion lookup (e.g., 'command_center' -> 'Command Center')
  const snakeAsWords = lower.replace(/_/g, " ");
  for (const [k, val] of Object.entries(targetDict)) {
    if (k.toLowerCase() === snakeAsWords) {
      return val;
    }
  }

  // 5. Fallback to English dict if non-empty
  if (translations.en[key] !== undefined) {
    return translations.en[key];
  }

  // 6. Return original string if not in dictionary
  return key;
}
